def normalize_jockey_name(name: str) -> str:
    """
    騎手名を正規化（netkeiba短縮形からナレッジファイルの形式に変換）
    
    Args:
        name: 騎手名（netkeiba短縮形またはフルネーム）
        
    Returns:
        正規化された騎手名（ナレッジファイルでの形式）
    """
    # 前後の空白を除去（半角・全角両方）
    name = name.strip().strip('　')
    
    # まずマッピングテーブルで変換を試みる
    if name in JOCKEY_NAME_MAP:
        return JOCKEY_NAME_MAP[name]
    
    # netkeiba形式（3文字）の場合の逆引き処理
    if len(name) == 3:
        # 横山系の処理（横山○ → 横山○○を探す）
        if name.startswith('横山'):
            third_char = name[2]
            # 横山武、横山和、横山琉、横山典から探す
            candidates = {
                '武': '横山武史',
                '和': '横山和生',
                '琉': '横山琉人',
                '典': '横山典弘',
                '史': '横山武史',
                '生': '横山和生',
                '人': '横山琉人',
                '弘': '横山典弘'
            }
            if third_char in candidates:
                return candidates[third_char]
        
        # 吉田系の処理
        elif name.startswith('吉田'):
            third_char = name[2]
            candidates = {
                '豊': '吉田豊',
                '隼': '吉田隼人',
                '人': '吉田隼人',
                '浩': '吉田晃浩',
                '治': '吉田順治'
            }
            if third_char in candidates:
                return candidates[third_char]
        
        # その他の一般的な3文字変換（川端系など）
        # 既に3文字の騎手はそのまま返す可能性が高い
    
    # 特殊なケース：全角スペースが必要な騎手
    # 騎手ナレッジファイルでスペースが含まれている主要騎手
    space_required = {
        '武豊': '武豊　　',  # 全角スペース2つ
        '武藤雅': '武藤雅　',  # 全角スペース1つ
    }
    
    if name in space_required:
        return space_required[name]
    
    # それ以外は元の名前を返す
    return name